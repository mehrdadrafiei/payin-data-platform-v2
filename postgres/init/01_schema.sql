-- Source operational DB (simulated payment company). Amounts are in rials.
CREATE SCHEMA IF NOT EXISTS core;

CREATE TABLE core.merchants (
    merchant_id        BIGINT PRIMARY KEY,
    name               TEXT        NOT NULL,
    mcc                VARCHAR(4)  NOT NULL,
    province           TEXT        NOT NULL,
    risk_level         TEXT        NOT NULL CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    owner_national_id  VARCHAR(10) NOT NULL,
    owner_mobile       VARCHAR(11) NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE core.transactions (
    transaction_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id     BIGINT      NOT NULL REFERENCES core.merchants (merchant_id),
    channel         TEXT        NOT NULL CHECK (channel IN ('POS', 'IPG', 'QR')),
    card_bin        VARCHAR(6)  NOT NULL,
    amount          BIGINT      NOT NULL,
    fee_amount      BIGINT      NOT NULL,
    status          TEXT        NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- CDC user: replication + read for the snapshot. No write access.
CREATE ROLE cdc WITH LOGIN REPLICATION PASSWORD 'cdc_pw';
GRANT USAGE ON SCHEMA core TO cdc;
GRANT SELECT ON ALL TABLES IN SCHEMA core TO cdc;
ALTER DEFAULT PRIVILEGES IN SCHEMA core GRANT SELECT ON TABLES TO cdc;

-- Publication created by us (Debezium does not need ownership of the tables).
CREATE PUBLICATION payin_pub FOR TABLE core.merchants, core.transactions;
